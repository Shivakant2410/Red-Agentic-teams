"""T4 — EventJournal backward compatibility (tests-FIRST requirement).

The golden fixtures in tests/fixtures/journal/ were generated by
scripts/make_golden_fixtures.py against the PRE-schema-change code and
committed BEFORE the C4 generalization landed. These tests prove the
generalization changed nothing for existing records, and validate the new
per-type contract.
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest

from redteam.attack_tree import AttackTree
from redteam.swarm.hypotheses import HypothesisRegistry
from redteam.swarm.journal import (CORE_REQUIRED_EVENT_FIELDS,
                                   EngagementMismatchError, EventJournal,
                                   JournalError, required_fields_for)
from redteam.swarm.projections import replay

FIXTURES = Path(__file__).resolve().parent / "fixtures" / "journal"


def _snapshot(reg) -> list[dict]:
    rows = []
    for h in sorted(reg.list(include_terminal=True, limit=1000),
                    key=lambda x: x.hypothesis_id):
        rows.append({"hypothesis_id": h.hypothesis_id, "status": h.status,
                     "owner": h.owner, "version": h.version,
                     "lease_expires_at": h.lease_expires_at,
                     "asset_ref": h.asset_ref,
                     "weakness_class": h.weakness_class,
                     "evidence": [e.get("evidence_id") for e in h.evidence_refs],
                     "counter_evidence": [e.get("evidence_id")
                                          for e in h.counter_evidence_refs],
                     "related": sorted(str(r) for r in h.related_hypotheses)})
    return rows


def test_golden_swarm_journal_replays_byte_identically():
    """The pre-change replay expectation is reproduced EXACTLY after the
    schema generalization: report summary AND projected registry state."""
    expect = json.loads((FIXTURES / "golden_swarm_replay.json").read_text())
    reg, report = replay(FIXTURES / "golden_swarm_journal.jsonl", "golden-eng")
    assert report.summary() == expect["report"]
    rows = _snapshot(reg)
    for row in rows:
        row["finding_id"] = ""          # the fixture snapshot's constant slot
    assert rows == expect["state"]


def test_golden_journal_event_types_all_in_swarm_table():
    """Every type the golden journal uses still requires hypothesis_id —
    the swarm contract is untouched."""
    lines = (FIXTURES / "golden_swarm_journal.jsonl").read_text().splitlines()
    types = {json.loads(line)["type"] for line in lines}
    assert types, "golden journal must be non-empty"
    for etype in types:
        assert required_fields_for(etype) == ("hypothesis_id",), etype


def test_swarm_append_without_hypothesis_id_still_rejected():
    journal = EventJournal("eng-1")
    base = {"event_id": "e1", "engagement_id": "eng-1", "type": "CLAIMED",
            "actor": "a", "ts": "t", "payload": {"detail": ""}}
    with pytest.raises(JournalError):
        journal.append(dict(base))                      # no hypothesis_id
    with pytest.raises(EngagementMismatchError):
        journal.append(dict(base, event_id="e2", engagement_id="eng-9",
                            hypothesis_id="hyp-1"))


def test_mission_types_require_their_identity_fields():
    journal = EventJournal("eng-1")
    base = {"event_id": "e1", "engagement_id": "eng-1", "type": "TASK_CLAIMED",
            "actor": "a", "ts": "t", "payload": {"detail": ""}}
    with pytest.raises(JournalError):
        journal.append(dict(base))                       # no mission_id/task_id
    with pytest.raises(JournalError):
        journal.append(dict(base, mission_id="m-1"))     # no task_id
    stored = journal.append(dict(base, mission_id="m-1", task_id="task-1"))
    assert stored["seq"] == 1
    # MISSION_ types need only mission_id; AGENT_/TREE_ same rule.
    ok = EventJournal("eng-1")
    ok.append({"event_id": "e2", "engagement_id": "eng-1",
               "type": "MISSION_STARTED", "mission_id": "m-1",
               "actor": "a", "ts": "t", "payload": {"detail": ""}})
    ok.append({"event_id": "e3", "engagement_id": "eng-1",
               "type": "TREE_RELEASED", "mission_id": "m-1",
               "actor": "a", "ts": "t", "payload": {"detail": ""}})


def test_mixed_journal_replay_skips_foreign_entity_events(tmp_path):
    """One engagement, both layers' events in ONE file: hypothesis replay
    applies swarm events and SKIPS mission events (counted, never fatal) —
    exactly as it did before the generalization (they were malformed then too)."""
    path = tmp_path / "_tmp_mixed_journal.jsonl"
    journal = EventJournal("eng-1", path=path)
    reg = HypothesisRegistry("eng-1", journal=journal)
    reg.register(asset_ref="a", weakness_class="w", claim="c",
                 created_by="synthesis")
    journal.append({"event_id": "m-e1", "engagement_id": "eng-1",
                    "type": "TASK_CLAIMED", "mission_id": "m-1",
                    "task_id": "task-1", "actor": "sched", "ts": "t",
                    "payload": {"detail": ""}})
    reg, report = replay(path, "eng-1")
    assert report.summary()["events_read"] == 2
    assert report.summary()["events_applied"] == 1
    assert report.summary()["invalid_skipped"] == 1


def test_core_guarantees_unchanged(tmp_path):
    """Torn lines, duplicate event_id idempotence, engagement mismatch —
    all exactly as before (golden T4.5)."""
    path = tmp_path / "j.jsonl"
    good = json.dumps({"event_id": "e1", "engagement_id": "eng-1",
                       "type": "REGISTERED", "hypothesis_id": "hyp-1",
                       "actor": "a", "ts": "t",
                       "payload": {"detail": ""}, "seq": 1})
    path.write_text(good + "\n{torn line...\n" + good + "\n")
    # Two historical rows sharing one event_id load as-is — the journal never
    # rewrites history; the APPEND path is what dedupes.
    journal = EventJournal("eng-1", path=path)
    assert len(journal.read_all()) == 2                # torn line skipped
    stored = journal.append(json.loads(good))          # duplicate id: idempotent
    assert stored["seq"] == 1
    assert len(journal.read_all()) == 2                # no third row, no new seq
    with pytest.raises(EngagementMismatchError):
        EventJournal("eng-2", path=path).append(json.loads(good))


def test_unknown_type_carries_core_only(tmp_path):
    """A NEW layer may start writing before the per-type table learns its
    type: unknown types validate the core identity set only (documented C4)."""
    journal = EventJournal("eng-1")
    stored = journal.append({"event_id": "e9", "engagement_id": "eng-1",
                             "type": "FUTURE_LAYER_EVENT", "actor": "a",
                             "ts": "t", "payload": {"detail": ""}})
    assert stored["seq"] == 1


def test_old_format_attack_tree_loads_unchanged(tmp_path):
    """The pre-Phase-2 attack_tree.json (five fields only) loads with the new
    dataclass defaults, and legacy positional claim() keeps working byte-
    identically (no owner, no lease stamped). Works on a COPY — the committed
    fixture must never be mutated by a test."""
    import shutil
    work = tmp_path / "attack_tree.json"
    shutil.copy(FIXTURES / "golden_attack_tree_old_format.json", work)
    tree = AttackTree(path=work)
    node = tree.node("access.idor", "https://target.test/api/users/7")
    assert node is not None and node.status == "in_progress"
    assert node.owner == "" and node.lease_expires_at == ""   # additive defaults
    assert tree.node("injection.sqli", "https://target.test/search").status == "todo"
    # Legacy positional claim: works, and CLEARS any stale lease fields.
    # (Work on a COPY — the fixture file itself must never be mutated.)
    assert tree.claim("injection.sqli", "https://target.test/search")
    legacy = tree.node("injection.sqli", "https://target.test/search")
    assert legacy.status == "in_progress"
    assert legacy.owner == "" and legacy.lease_expires_at == ""
    # Core-required-fields tuple is exported for introspection.
    assert "event_id" in CORE_REQUIRED_EVENT_FIELDS
